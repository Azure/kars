import { createHash, createPrivateKey, randomBytes } from "node:crypto";
import { SignJWT, jwtVerify } from "jose";
import { oidcConfig } from "./oidc-config";

export const GITHUB_APP_FLOW_COOKIE = "bridge-github-app-registration";
export const GITHUB_APP_CALLBACK = "/console/configuration/github-app/callback";
export const GITHUB_APP_FLOW_PATH = "/console/configuration/github-app";
export const GITHUB_APP_FLOW_SECONDS = 3600;
const AUDIENCE = "kars:github-app-registration";
const MAX_PEM_BYTES = 16 * 1024;

export class GithubAppInputError extends Error {}

export function githubAppOrigin(headers: Pick<Headers, "get">, sameOrigin = false): string {
  const protocol = headers.get("x-forwarded-proto") ?? "http";
  const host = headers.get("x-forwarded-host") ?? headers.get("host");
  if (!host || !["http", "https"].includes(protocol)) throw new Error("invalid_origin");
  const url = new URL(`${protocol}://${host}`);
  if (url.host !== host || url.username || url.password || url.pathname !== "/" || url.search || url.hash
    || (url.protocol !== "https:" && !["localhost", "127.0.0.1", "[::1]"].includes(url.hostname))) {
    throw new Error("invalid_origin");
  }
  if (sameOrigin && headers.get("origin") !== url.origin) throw new Error("invalid_origin");
  return url.origin;
}

export async function readGithubAppPem(form: FormData): Promise<{ app_id: string; private_key: string }> {
  const id = form.get("app_id");
  const file = form.get("private_key_file");
  if (typeof id !== "string" || !/^\d{1,20}$/.test(id.trim())) {
    throw new GithubAppInputError("Enter the numeric App ID from the App’s GitHub settings.");
  }
  if (!(file instanceof File) || file.size === 0 || file.size > MAX_PEM_BYTES) {
    throw new GithubAppInputError("Choose the GitHub-generated .pem private-key file (up to 16 KiB).");
  }
  const pem = (await file.text()).trim();
  try {
    if (!/^-----BEGIN (?:RSA )?PRIVATE KEY-----[\s\S]+-----END (?:RSA )?PRIVATE KEY-----$/.test(pem)
      || createPrivateKey(pem).asymmetricKeyType !== "rsa") throw new Error();
  } catch {
    throw new GithubAppInputError("This is not an unencrypted RSA private-key PEM. Choose the .pem file generated by GitHub, not a public key or webhook secret.");
  }
  return { app_id: id.trim(), private_key: pem };
}

export function githubAppManifest(form: FormData, origin: string) {
  const name = form.get("name");
  const owner = form.get("owner");
  const organization = form.get("organization");
  const visibility = form.get("visibility");
  if (typeof name !== "string" || !/^[A-Za-z0-9][A-Za-z0-9 ._-]{0,33}$/.test(name.trim())) {
    throw new GithubAppInputError("Choose an App name of 1–34 letters, numbers, spaces, dots, underscores or hyphens.");
  }
  if (owner !== "personal" && owner !== "organization") throw new GithubAppInputError("Choose a personal or organization owner.");
  if (visibility !== "private" && visibility !== "public") throw new GithubAppInputError("Choose the App’s installation visibility.");
  if (owner === "organization" && (typeof organization !== "string"
    || !/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?$/.test(organization.trim()))) {
    throw new GithubAppInputError("Enter the organization’s GitHub login, not a URL.");
  }
  const endpoint = owner === "organization"
    ? `https://github.com/organizations/${encodeURIComponent((organization as string).trim())}/settings/apps/new`
    : "https://github.com/settings/apps/new";
  const permissions: Record<string, string> = {
    contents: "write", issues: "write", pull_requests: "write",
    actions: "read", metadata: "read", checks: "read", statuses: "read",
  };
  if (form.get("security_signals") === "on") {
    Object.assign(permissions, { vulnerability_alerts: "read", security_events: "read", secret_scanning_alerts: "read" });
  }
  return {
    endpoint,
    manifest: {
      name: name.trim(), url: origin,
      description: "Kars workspace repository access and reviewed engineering workflows.",
      redirect_url: `${origin}${GITHUB_APP_CALLBACK}`,
      public: visibility === "public",
      hook_attributes: { url: `${origin}/`, active: false },
      default_permissions: permissions, default_events: [],
      request_oauth_on_install: false,
    },
  };
}

function sessionBinding(token: string): string {
  return createHash("sha256").update(token).digest("hex");
}

export async function createGithubAppFlow(sessionToken: string, origin: string) {
  const cfg = oidcConfig();
  if (!cfg) throw new Error("sso_required");
  const state = randomBytes(32).toString("base64url");
  const token = await new SignJWT({ state, origin, session: sessionBinding(sessionToken) })
    .setProtectedHeader({ alg: "HS256" }).setIssuer("kars-bridge").setAudience(AUDIENCE)
    .setIssuedAt().setExpirationTime(`${GITHUB_APP_FLOW_SECONDS}s`)
    .sign(new TextEncoder().encode(cfg.sessionSecret));
  return { state, token };
}

export async function verifyGithubAppFlow(
  token: string, sessionToken: string, state: string, origin: string,
): Promise<boolean> {
  const cfg = oidcConfig();
  if (!cfg || !/^[A-Za-z0-9_-]{43}$/.test(state)) return false;
  try {
    const { payload } = await jwtVerify(token, new TextEncoder().encode(cfg.sessionSecret), {
      algorithms: ["HS256"], issuer: "kars-bridge", audience: AUDIENCE,
      maxTokenAge: GITHUB_APP_FLOW_SECONDS,
    });
    return payload.state === state && payload.origin === origin && payload.session === sessionBinding(sessionToken);
  } catch {
    return false;
  }
}
