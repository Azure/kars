export interface CustomRule {
  id: number;
  name: string;
  effect: "allow" | "deny";
  actions: string; // comma/space separated
  priority: number;
}

function yamlList(actions: string[]): string {
  return actions.map((a) => `      - "${a}"`).join("\n");
}

/** Generate the agentmesh PolicyEngine YAML from selected presets + custom rules. */
export function generateAgtProfile(
  agent: string,
  presetIds: Set<string>,
  custom: CustomRule[],
): string {
  const rules: string[] = [];
  for (const p of POLICY_PRESETS) {
    if (!presetIds.has(p.id)) continue;
    const key = p.effect === "deny" ? "denied_actions" : "allowed_actions";
    rules.push(
      `  - name: ${p.id}\n    type: capability\n    ${key}:\n${yamlList(p.actions)}\n    priority: ${p.priority}`,
    );
  }
  for (const c of custom) {
    const actions = c.actions.split(/[\s,]+/).map((s) => s.trim()).filter(Boolean);
    if (!c.name.trim() || actions.length === 0) continue;
    const key = c.effect === "deny" ? "denied_actions" : "allowed_actions";
    const safeName = c.name.trim().toLowerCase().replace(/[^a-z0-9-]+/g, "-");
    rules.push(
      `  - name: ${safeName}\n    type: capability\n    ${key}:\n${yamlList(actions)}\n    priority: ${c.priority}`,
    );
  }
  return [
    "# Generated by the kars Bridge policy builder — agentmesh PolicyEngine format.",
    "# Rules are evaluated by priority (higher first); first match wins.",
    'version: "1.0"',
    `agent: ${agent || "custom-policy"}`,
    "policies:",
    rules.join("\n"),
    "",
  ].join("\n");
}

/** Build the full ToolPolicy spec object from the builder inputs. */
export function buildToolPolicySpec(opts: {
  agent: string;
  sandboxLabelKey: string;
  sandboxLabelValue: string;
  toolGlob: string;
  presetIds: Set<string>;
  custom: CustomRule[];
  approvalMode: "none" | "always" | "aboveThreshold";
  approvalThreshold: string;
}): Record<string, unknown> {
  const appliesTo: Record<string, unknown> = {};
  if (opts.sandboxLabelKey.trim()) {
    appliesTo.sandboxMatchLabels = { [opts.sandboxLabelKey.trim()]: opts.sandboxLabelValue.trim() || "true" };
  }
  if (opts.toolGlob.trim() && opts.toolGlob.trim() !== "*") {
    appliesTo.tool = opts.toolGlob.trim();
  }
  const spec: Record<string, unknown> = {
    appliesTo,
    agtProfile: { inline: generateAgtProfile(opts.agent, opts.presetIds, opts.custom) },
  };
  if (opts.approvalMode !== "none") {
    const approval: Record<string, unknown> = { mode: opts.approvalMode };
    if (opts.approvalMode === "aboveThreshold" && opts.approvalThreshold.trim()) {
      approval.threshold = opts.approvalThreshold.trim();
    }
    spec.approval = approval;
  }
  return spec;
}
