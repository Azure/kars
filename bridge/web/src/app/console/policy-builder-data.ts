// kars Bridge — structured AGT tool-policy builder. Instead of hand-writing the
// agentmesh PolicyEngine YAML (the "embarrassing" part), the operator toggles
// capability presets and adds optional custom allow/deny rules; this module
// generates a valid ToolPolicy spec (appliesTo + agtProfile.inline YAML).
//
// The AGT DSL: `policies:` is a priority-ordered list of rules; each rule has a
// type (capability), an allow (`allowed_actions`) or deny (`denied_actions`)
// list of glob action patterns, and a priority (higher = evaluated first, first
// match wins). Action format examples: shell:<cmd>, inference:*, tool:<name>,
// foundry:<tool>:*, spawn:create:*, mesh:send:*.

export interface PolicyPreset {
  id: string;
  label: string;
  description: string;
  effect: "allow" | "deny";
  actions: string[];
  priority: number;
  /** On by default in a new policy (safe, common baseline). */
  defaultOn: boolean;
}

