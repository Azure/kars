"""Reproduce the narrowly patched Headlamp tool from its immutable upstream archive."""

import argparse
import base64
import gzip
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "headlamp-plugin-0.13.1-kars.tgz"
FRONTEND = ROOT.parents[2] / "sandbox-images/headlamp/build-frontend.mjs"


def replace_once(text, before, after):
    if text.count(before) != 1:
        raise ValueError("Unexpected upstream polyfill consumer")
    return text.replace(before, after)


def polyfill_source():
    source = FRONTEND.read_text()
    start = "export function productionPolyfills(inject, resolve) {"
    end = "\nexport function verifyProductionLock("
    if source.count(start) != 1 or source.count(end) != 1:
        raise ValueError("Review changed canonical frontend polyfill implementation")
    implementation = source[source.index(start):source.index(end)].rstrip() + "\n"
    return ("// Copyright (c) Microsoft Corporation.\n// Licensed under the MIT License.\n"
            "// Generated by build-tool/prepare.py from the maintained frontend implementation.\n"
            'import assert from "node:assert/strict";\n'
            'import { createRequire } from "node:module";\n'
            + implementation
            + 'const require = createRequire(import.meta.url);\n'
            + 'export default productionPolyfills(require("@rollup/plugin-inject"), require.resolve);\n').encode()


def prepare(upstream_bytes):
    provenance = json.loads((ROOT / "upstream.json").read_text())
    digest = "sha512-" + base64.b64encode(hashlib.sha512(upstream_bytes).digest()).decode()
    if digest != provenance["integrity"]:
        raise ValueError("Upstream Headlamp tool integrity mismatch")
    files = {}
    with tarfile.open(fileobj=io.BytesIO(upstream_bytes), mode="r:gz") as archive:
        for entry in archive.getmembers():
            name = PurePosixPath(entry.name)
            if name.is_absolute() or ".." in name.parts or not name.parts or name.parts[0] != "package":
                raise ValueError("Unexpected upstream archive path")
            if entry.isdir():
                continue
            if not entry.isfile() or entry.name in files:
                raise ValueError("Unexpected upstream archive entry")
            files[entry.name] = (archive.extractfile(entry).read(), entry.mode)
    manifest_path = "package/package.json"
    manifest = json.loads(files[manifest_path][0])
    if manifest["name"] != provenance["name"] or manifest["version"] != provenance["version"]:
        raise ValueError("Unexpected upstream package identity")
    if manifest["dependencies"].pop("vite-plugin-node-polyfills") != "^0.23.0":
        raise ValueError("Unexpected upstream polyfill dependency")
    for name, version in provenance["replacements"].items():
        if manifest["dependencies"].get(name) != provenance["existingRequirements"].get(name):
            raise ValueError("Review existing direct polyfill dependency")
        manifest["dependencies"][name] = version
    auth_path = "package/official-plugins/keda/test-files/deploy/authentication.yaml"
    auth, auth_mode = files[auth_path]
    if hashlib.sha256(auth).hexdigest() != provenance["sourceHashes"][auth_path.removeprefix("package/")]:
        raise ValueError("Review changed upstream KEDA credential example")
    documents = [document.strip() for document in auth.decode().split("---")]
    kinds = [next(line for line in document.splitlines() if line.startswith("kind: "))
             for document in documents]
    if kinds != ["kind: Secret", "kind: TriggerAuthentication", "kind: Secret", "kind: TriggerAuthentication"]:
        raise ValueError("Unexpected upstream KEDA authentication resources")
    auth = ("\n---\n".join(documents[index] for index in (1, 3)) + "\n").encode()
    files[auth_path] = (auth, auth_mode)
    guide = (ROOT / "keda-example-credentials.md").read_bytes()
    guide_path = "package/official-plugins/keda/test-files/deploy/README.md"
    if guide_path in files:
        raise ValueError("Review existing upstream KEDA credential instructions")
    files[guide_path] = (guide, 0o644)
    helper = polyfill_source()
    manifest["karsPatch"] = {
        "upstream": provenance,
        "consumer": "config/vite.config.mjs",
        "description": "Use canonical process/buffer/stream polyfills and externally provisioned KEDA credentials; retain all tool commands",
        "polyfillsSha256": hashlib.sha256(helper).hexdigest(),
        "exampleAuthentication": {
            "path": auth_path.removeprefix("package/"),
            "sha256": hashlib.sha256(auth).hexdigest(),
            "credentialsGuide": guide_path.removeprefix("package/"),
            "credentialsGuideSha256": hashlib.sha256(guide).hexdigest(),
            "description": "Remove only embedded example Secrets; preserve both TriggerAuthentication resources and every workload consumer",
        },
    }
    files[manifest_path] = ((json.dumps(manifest, indent=2) + "\n").encode(), files[manifest_path][1])
    config_path = "package/config/vite.config.mjs"
    config = files[config_path][0].decode()
    for before, after in [
        ("import { nodePolyfills } from 'vite-plugin-node-polyfills';", "import polyfills from './kars-polyfills.mjs';"),
        ("import { fileURLToPath } from 'url';\n", ""),
        ("    nodePolyfills({\n      include: ['process', 'buffer', 'stream'],\n    }),", "    polyfills,"),
        ("  resolve: {\n    alias: [\n      {\n        find: /^(vite-plugin-node-polyfills\\/shims\\/.+)/,\n        replacement: '$1',\n        customResolver(source) {\n          const resolved = import.meta.resolve(source);\n          return fileURLToPath(resolved);\n        },\n      },\n    ],\n  },\n", ""),
    ]:
        config = replace_once(config, before, after)
    files[config_path] = (config.encode(), files[config_path][1])
    files["package/config/kars-polyfills.mjs"] = (helper, 0o644)
    files["package/KARS-PATCH.json"] = ((json.dumps(manifest["karsPatch"], indent=2) + "\n").encode(), 0o644)
    files["package/KARS-LICENSE"] = ((ROOT.parent / "checker/LICENSE").read_bytes(), 0o644)
    license = (ROOT / "LICENSE.upstream").read_bytes()
    if hashlib.sha256(license).hexdigest() != provenance["licenseSha256"]:
        raise ValueError("Upstream license integrity mismatch")
    files["package/UPSTREAM-LICENSE"] = (license, 0o644)
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.GNU_FORMAT) as archive:
        for name, (content, mode) in sorted(files.items()):
            entry = tarfile.TarInfo(name)
            entry.size, entry.mode, entry.mtime = len(content), mode, 0
            archive.addfile(entry, io.BytesIO(content))
    output = io.BytesIO()
    with gzip.GzipFile(fileobj=output, mode="wb", filename="", mtime=0, compresslevel=9) as compressed:
        compressed.write(raw.getvalue())
    return output.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, help="Original archive; pinned SHA-512 is always verified")
    parser.add_argument("--check", action="store_true", help="Check the committed archive without writing")
    args = parser.parse_args()
    if args.upstream:
        upstream = args.upstream.read_bytes()
    else:
        provenance = json.loads((ROOT / "upstream.json").read_text())
        with urllib.request.urlopen(provenance["url"], timeout=30) as response:
            upstream = response.read(16 * 1024 * 1024 + 1)
    prepared = prepare(upstream)
    if args.check:
        if OUTPUT.read_bytes() != prepared:
            raise ValueError("Packaged Headlamp tool does not match the reviewed recipe/source")
        print("Headlamp tool archive matches pinned upstream and canonical polyfills")
    else:
        OUTPUT.write_bytes(prepared)
        print(f"Wrote {OUTPUT.name}: sha256:{hashlib.sha256(prepared).hexdigest()}")


if __name__ == "__main__":
    main()
